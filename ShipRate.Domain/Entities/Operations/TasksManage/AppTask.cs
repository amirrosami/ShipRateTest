using ShipRate.Domain.Entities.Base;
using ShipRate.Domain.Entities.BaseInfo.Generals;
using ShipRate.Domain.Entities.Security;

namespace ShipRate.Domain.Entities.Operations.TasksManage
{
    public class TaskCategory : SystemEntity
    {
        public string TaskCategoryName { get; set; }
        public string TaskCategoryLocalName { get; set; } = string.Empty;
        //Relations
        public List<Task> Tasks { get; set; }
    }

    public class Task : SystemEntity
    {
        public int SortOrder { get; set; }
        public string TaskName { get; set; }
        public string TaskLocalName { get; set; }
        public int TaskCategoryId { get; set; }
        public int DefaultPriorityId { get; set; }
        public int DefaultDueDays { get; set; }
        public string Description { get; set; }

        //Relations
        public FollowUpPriority DefaultPriority { get; set; }
        public TaskCategory TaskCategory { get; set; }
        public List<TaskCheckListTemplate> TaskCheckListTemplates { get; set; }
    }

    public class TaskCheckListTemplate : BusinessEntity
    {
        public int TaskId { get; set; }
        public int SortOrder { get; set; }
        public string CheckListItemTitle { get; set; }
        public string Description { get; set; }
        public bool IsMandatory { get; set; }   //اگر 1 باشد در صورت عدم چک تسک مربوه کامپلیت نمیشود
        //Relations
        public Task Task { get; set; }
    }
    public class TaskSourceType : SystemEntity
    {
        public string TaskSourceName { get; set; } = null!;
        public string TaskSourceLocalName { get; set; } = null!;
        public int SortOrder { get; set; }
    }
    public class AppTask : BusinessEntity
    {

        public int? TaskId { get; set; }
        public string Title { get; set; } = null!;
        public string TaskDesciption { get; set; }
        public int? PriorityId { get; set; }
        public int? SourceTypeId { get; set; }


        public int? EntityTypeId { get; set; }
        public Guid? RelatedEntityId { get; set; }


        public Guid? OwnerUserId { get; set; }
        public Guid? AssignedByUserId { get; set; }
        public DateTime? AssignDate { get; set; }

        public DateTime? DueDate { get; set; }
        public DateTime? StartedDate { get; set; }
        public DateTime? CompletedDate { get; set; }

        public int TaskStatusId { get; set; }
        public string ResultNotes { get; set; }
        public bool IsAutoGenerated { get; set; } = false;


        //Relations
        public TaskSourceType SourceType { get; set; }
        public EntityType EntityType { get; set; }
        public FollowUpPriority Priority { get; set; }
        public ApplicationUser OwnerUser { get; set; }
        public ApplicationUser AssignedByUser { get; set; }
        public BaseInfo.Generals.TaskStatus TaskStatus { get; set; }
        public Task Task { get; set; }


        public List<AppTaskComment> Comments { get; set; } = new();
        public List<AppTaskCheckList> CheckLists { get; set; } = new();
        public List<AppTaskAssignment> Assignments { get; set; } = new();
        public List<AppTaskReminder> Reminders { get; set; } = new();
        public List<AppTaskEscalation> Escalations { get; set; } = new();


    }

    public class AppTaskComment : BusinessEntity
    {
        public Guid? AppTaskId { get; set; }
        public int CommentTypeId { get; set; }
        public string CommentText { get; set; }
        public bool IsInternal { get; set; }
        //Relations
        public AppTask AppTask { get; set; }
        public CommentType CommentType { get; set; }
        public ApplicationUser CreatedByUser { get; set; }
    }

    public class AppTaskCheckList : BusinessEntity
    {
        public Guid AppTaskId { get; set; }
        public int SortOrder { get; set; }
        public string CheckListItemTitle { get; set; }
        public string Description { get; set; }
        public bool IsChecked { get; set; }
        public Guid? CheckedByUserId { get; set; }
        public DateTime? CheckedDate { get; set; }
        public bool IsMandatory { get; set; }   //اگر 1 باشد در صورت عدم چک تسک مربوه کامپلیت نمیشود
        //Relations
        public AppTask AppTask { get; set; }
        public ApplicationUser CheckedByUser { get; set; }
    }


    public class AppTaskAssignment : BusinessEntity
    {
        public Guid AppTaskId { get; set; }
        public Guid AssignedToUserId { get; set; }
        public Guid? AssignedByUserId { get; set; }

        public string? Note { get; set; }

        public DateTime AssignedAt { get; set; } = DateTime.Now;
        public DateTime? AcceptedAt { get; set; }
        public DateTime? RejectedAt { get; set; }

        public bool IsCurrent { get; set; } = true;
        //Relations
        public AppTask AppTask { get; set; }
        public ApplicationUser AssignedToUser { get; set; }
        public ApplicationUser AssignedByUser { get; set; }

    }

    public class AppTaskReminder : BusinessEntity
    {
        public Guid AppTaskId { get; set; }
        public DateTime ReminderAt { get; set; }

        public bool IsSent { get; set; } = false;
        public DateTime? SentAt { get; set; }

        public string? Channel { get; set; }              // System, SMS, Email, WhatsApp
        public string? Note { get; set; }

        //Relations
        public AppTask AppTask { get; set; }
    }
    public class AppTaskEscalation : BusinessEntity
    {
        public Guid AppTaskId { get; set; }

        public Guid EscalatedToUserId { get; set; }
        public Guid? EscalatedByUserId { get; set; }

        public string Reason { get; set; } = null!;
        public string? Note { get; set; }

        public bool IsResolved { get; set; } = false;
        public DateTime? ResolvedAt { get; set; }

        //Relations
        public AppTask AppTask { get; set; }
        public ApplicationUser EscalatedToUser { get; set; }
        public ApplicationUser EscalatedByUser { get; set; }

    }
}
